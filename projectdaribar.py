def normalize_composition(value):
    if pd.isna(value):
        return np.nan

    # Разделяем комбинированный препарат на вещества
    parts = [
        part.strip()
        for part in value.split(',')
        if part.strip()
    ]

    normalized_parts = []

    for part in parts:
        # Приводим вариант к стандартному названию
        part = ingredient_map.get(part, part)

        # Убираем вспомогательные вещества
        if part in not_active_components:
            continue

        normalized_parts.append(part)

    # Удаляем повторяющиеся компоненты
    normalized_parts = list(dict.fromkeys(normalized_parts))

    # Сортируем, чтобы порядок веществ не влиял на группировку
    normalized_parts = sorted(normalized_parts)

    if not normalized_parts:
        return np.nan

    return ', '.join(normalized_parts)

