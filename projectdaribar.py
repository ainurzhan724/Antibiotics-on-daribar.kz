def get_info_med(url):
    response = requests.get(url, headers=headers)
    soup = BeautifulSoup(response.text, "html.parser")

    # Название
    name = soup.find("meta", itemprop="name")
    name = name["content"] if name else None

    # Цена
    price = soup.find("span", itemprop="price")
    price = int(price.get_text(strip=True)) if price else None

    # Характеристики
    characteristics = {}

    blocks = soup.find_all("div", class_="product-details_contentContainer__nZrZV")

    for block in blocks:
        h2 = block.find("h2")
        info = block.find("div", class_="product-details_characteristicsInfo__g2T9J")

        if h2 and info:
            key = h2.get_text(strip=True).replace(":", "")
            value = info.get_text(strip=True)
            characteristics[key] = value

    return {
        "url": url,
        "Название": name,
        "Цена": price,
        "Производитель": characteristics.get("Производитель"),
        "Страна производитель": characteristics.get("Страна производитель"),
        "Действующее вещество": characteristics.get("Действующее вещество"),
        "Лекарственная форма": characteristics.get("Лекарственная форма"),
    }

