import re
import unicodedata


def clean_active_ingredient(value):
    if pd.isna(value):
        return np.nan

    value = str(value)

    # Нормализация символов Unicode
    value = unicodedata.normalize('NFKC', value)

    # Нижний регистр
    value = value.lower()

    # ё → е
    value = value.replace('ё', 'е')

    # Исправляем латинские буквы, случайно попавшие в русские слова
    value = re.sub(r'^cульфаметоксазол', 'сульфаметоксазол', value)
    value = re.sub(r'^tербинафин', 'тербинафин', value)

    # Разные разделители приводим к запятой
    value = re.sub(r'\s*[/+;]\s*', ', ', value)

    # Союз "и" между компонентами
    value = re.sub(r'\s+и\s+', ', ', value)

    # Исправляем пробелы около запятых
    value = re.sub(r'\s*,\s*', ', ', value)

    # Несколько запятых подряд
    value = re.sub(r',+', ',', value)

    # Несколько пробелов подряд
    value = re.sub(r'\s+', ' ', value)

    # Убираем точки, запятые и пробелы по краям
    value = value.strip(' ,.;')

    return value

